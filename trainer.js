// Обработка интерактивного мини-тренажера
window.checkQuiz = function(taskId) {
  const task = ALL_TASKS.find(t => t.id === taskId);
  if (!task || !task.quiz) return;

  const inputEl = document.getElementById(`quiz-input-${taskId}`);
  const resultEl = document.getElementById(`quiz-result-${taskId}`);
  if (!inputEl || !resultEl) return;

  const rawVal = inputEl.value.trim().toLowerCase().replace(',', '.');
  if (!rawVal) {
    resultEl.className = "quiz-result-box wrong";
    resultEl.style.display = "block";
    resultEl.innerHTML = "⚠️ Пожалуйста, введите ответ в поле ввода.";
    return;
  }

  // Проверяем соответствие
  const isMatch = task.quiz.answers.some(ans => {
    const norm = ans.toLowerCase().trim().replace(',', '.');
    return norm === rawVal;
  });

  resultEl.style.display = "block";
  if (isMatch) {
    resultEl.className = "quiz-result-box correct";
    resultEl.innerHTML = `
      <div>✅ <b>Правильно! Отличная работа!</b></div>
      <div style="margin-top: 6px; font-size: 13px;">${task.quiz.explanation}</div>
    `;
  } else {
    resultEl.className = "quiz-result-box wrong";
    resultEl.innerHTML = `
      <div>❌ <b>Пока неверно.</b> Попробуйте ещё раз!</div>
      <div style="margin-top: 6px;">
        <button class="quiz-explain-btn" onclick="showQuizExplanation('${taskId}')">Показать правильный ответ и разбор</button>
      </div>
    `;
  }

  renderKaTeX(resultEl);
};

