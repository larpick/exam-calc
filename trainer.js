// Переключение раскрытия решения
window.toggleSolution = function(taskId) {
  if (openSolutions.has(taskId)) {
    openSolutions.delete(taskId);
  } else {
    openSolutions.add(taskId);
  }
  renderCards();
};

// Переключение галочки "Выучено"
window.toggleLearned = function(taskId, isChecked) {
  const learnedSet = getLearnedSet();
  if (isChecked) {
    learnedSet.add(taskId);
  } else {
    learnedSet.delete(taskId);
  }
  saveLearnedSet(learnedSet);
  updateProgress();

  if (activeTab === "unlearned") {
    renderCards();
    return;
  }

  const card = document.getElementById(`card-${taskId}`);
  if (card) {
    if (isChecked) {
      card.classList.add("learned");
      const label = card.querySelector(".learn-check-label");
      if (label) label.textContent = "Выучено ✓";
    } else {
      card.classList.remove("learned");
      const label = card.querySelector(".learn-check-label");
      if (label) label.textContent = "Отметить как выученное";
    }
  }
};

// Кнопка: Показать / скрыть все решения
window.toggleAllSolutions = function() {
  const currentFiltered = getFilteredTasks();
  if (openSolutions.size > 0) {
    openSolutions.clear();
  } else {
    currentFiltered.forEach(t => openSolutions.add(t.id));
  }
  renderCards();
};

